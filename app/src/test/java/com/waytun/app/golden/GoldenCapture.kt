        for (raw in GoldenCorpus.titles) out.appendLine("        ${lit(raw)} to ${lit(SubscriptionClient.decodeTitle(raw))},")
        out.appendLine("    )")
        out.appendLine("    val usages: List<Pair<String, String?>> = listOf(")
        for (raw in GoldenCorpus.usages) out.appendLine("        ${lit(raw)} to ${lit(SubscriptionClient.parseUsage(raw)?.toString())},")
        out.appendLine("    )")
        out.appendLine("    val flagNames: List<Pair<String, String>> = listOf(")
        for (raw in GoldenCorpus.names) out.appendLine("        ${lit(raw)} to ${lit(FlagName.parse(raw).toString())},")
        out.appendLine("    )")

        out.appendLine("    val settingsJson: List<Pair<String, String>> = listOf(")
        for (s in GoldenCorpus.settings) out.appendLine("        ${lit(s.toJson())} to ${lit(s.toString())},")
        out.appendLine("    )")
        out.appendLine("    val profiles: List<ProfileGolden> = listOf(")
        for ((i, s) in GoldenCorpus.settings.withIndex()) {
            val p = ObfuscationGenerator.generate(s, Random(1000 + i), 1_700_000_000_000L + i)
            out.appendLine("        ProfileGolden(settingsIndex = $i, seed = ${1000 + i}, now = ${1_700_000_000_000L + i}L, profile = ${lit(p.toString())}, json = ${lit(p.toJson())}),")
        }
        out.appendLine("    )")
        out.appendLine("    val awg: List<Pair<String, String>> = listOf(")
        for (conf in GoldenCorpus.confs) out.appendLine("        ${lit(conf)} to ${lit(AwgConfigObfuscator.apply(conf, GoldenCorpus.profile))},")
        out.appendLine("    )")
        out.appendLine("    val profileJson: String = ${lit(GoldenCorpus.profile.toJson())}")
        out.appendLine("}")

        val target = System.getProperty("waytun.golden.out")
        if (target != null) File(target).apply { parentFile?.mkdirs() }.writeText(out.toString())
    }

    private fun xray(block: () -> String): String = try {
        block()
    } catch (e: Exception) {
        "ERR:${e.javaClass.simpleName}:${e.message}"
    }

    private fun list(values: List<String>): String = values.joinToString(", ", "listOf(", ")") { lit(it) }

    private fun lit(value: String?): String {
        if (value == null) return "null"
        val sb = StringBuilder("\"")
        for (c in value) {
            when (c) {
                '\\' -> sb.append("\\\\")
                '"' -> sb.append("\\\"")
                '$' -> sb.append("\\$")
                '\n' -> sb.append("\\n")
                '\r' -> sb.append("\\r")
                '\t' -> sb.append("\\t")
                else -> if (c.code < 0x20) sb.append("\\u%04x".format(c.code)) else sb.append(c)
            }
        }
        return sb.append('"').toString()
    }
}

